export type IconName = keyof typeof SF;

export const Icon = ({
  name,
  size = 20,
  color,
}: {
  name: IconName;
  size?: number;
  color: string;
}) => {
  if (process.env.EXPO_OS === 'ios') {
    return <SymbolView name={SF[name] as never} size={size} tintColor={color} />;
  }
  return <MaterialIcons name={MATERIAL[name] as never} size={size} color={color} />;
};
